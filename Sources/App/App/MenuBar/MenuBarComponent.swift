import Foundation

/// One menu bar component: up to two data lines rendered with a visual and a color rule.
struct MenuBarComponent: Codable, Equatable, Identifiable, Sendable {
    var id = UUID()
    var primary: DataField
    var secondary: DataField?
    /// Third value, only for the compact card layouts.
    var tertiary: DataField?
    var visual: ComponentVisual
    var colorMode: ColorMode = .monochrome
    var customColor: RGBAColor = .teal
    var gradientStart: RGBAColor = .green
    var gradientEnd: RGBAColor = .red
    var colorTarget: ColorTarget = .visual
    var showLabel = false
    var showValue = true
    var unit: ByteUnit = .auto
    var enabled = true
    var thresholds: Thresholds
    /// Set when the component was generated by a simple metric card (see `MetricCardConfig+Mapping`).
    var layout: MetricLayout?
    var battery = BatteryGlyphOptions()
    /// Sabitlenmiş cihaz (`DeviceBattery.id`); nil = Mac pili. Yalnızca `.batteryCapsule` görünümüyle anlamlıdır.
    var deviceID: String?
    var deviceName: String?
    /// Tıklayınca açılacak panel; nil = otomatik (birincil alanın metriği). Gelişmiş düzenleyicide seçilir.
    var panelKind: PanelKind?

    init(_ primary: DataField, _ secondary: DataField? = nil, tertiary: DataField? = nil, visual: ComponentVisual = .text,
         colorMode: ColorMode = .monochrome, colorTarget: ColorTarget = .visual,
         customColor: RGBAColor = .teal, gradientStart: RGBAColor = .green, gradientEnd: RGBAColor = .red,
         showLabel: Bool = false, showValue: Bool = true, unit: ByteUnit = .auto, layout: MetricLayout? = nil,
         battery: BatteryGlyphOptions = BatteryGlyphOptions()) {
        self.battery = battery
        self.primary = primary
        self.secondary = secondary
        self.tertiary = tertiary
        self.layout = layout
        self.visual = visual
        self.colorMode = colorMode
        self.colorTarget = colorTarget
        self.customColor = customColor
        self.gradientStart = gradientStart
        self.gradientEnd = gradientEnd
        self.showLabel = showLabel
        self.showValue = showValue
        self.unit = unit
        self.thresholds = primary.defaultThresholds
    }

    private enum CodingKeys: String, CodingKey {
        case id, primary, secondary, tertiary, visual, colorMode, customColor, gradientStart, gradientEnd
        case colorTarget, showLabel, showValue, unit, enabled, thresholds, layout, battery, deviceID, deviceName, panelKind
    }

    init(from decoder: any Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decodeIfPresent(UUID.self, forKey: .id) ?? UUID()
        primary = try c.decode(DataField.self, forKey: .primary)
        secondary = try? c.decodeIfPresent(DataField.self, forKey: .secondary)
        tertiary = try? c.decodeIfPresent(DataField.self, forKey: .tertiary)
        visual = (try? c.decodeIfPresent(ComponentVisual.self, forKey: .visual)) ?? .text
        colorMode = (try? c.decodeIfPresent(ColorMode.self, forKey: .colorMode)) ?? .monochrome
        customColor = try c.decodeIfPresent(RGBAColor.self, forKey: .customColor) ?? .teal
        gradientStart = try c.decodeIfPresent(RGBAColor.self, forKey: .gradientStart) ?? .green
        gradientEnd = try c.decodeIfPresent(RGBAColor.self, forKey: .gradientEnd) ?? .red
        colorTarget = (try? c.decodeIfPresent(ColorTarget.self, forKey: .colorTarget)) ?? .visual
        showLabel = try c.decodeIfPresent(Bool.self, forKey: .showLabel) ?? false
        showValue = try c.decodeIfPresent(Bool.self, forKey: .showValue) ?? true
        unit = (try? c.decodeIfPresent(ByteUnit.self, forKey: .unit)) ?? .auto
        enabled = try c.decodeIfPresent(Bool.self, forKey: .enabled) ?? true
        thresholds = try c.decodeIfPresent(Thresholds.self, forKey: .thresholds) ?? primary.defaultThresholds
        layout = try? c.decodeIfPresent(MetricLayout.self, forKey: .layout)
        battery = (try? c.decodeIfPresent(BatteryGlyphOptions.self, forKey: .battery)) ?? BatteryGlyphOptions()
        deviceID = try? c.decodeIfPresent(String.self, forKey: .deviceID)
        deviceName = try? c.decodeIfPresent(String.self, forKey: .deviceName)
        panelKind = try? c.decodeIfPresent(PanelKind.self, forKey: .panelKind)
        self = normalized()
    }

    var isValid: Bool { visual.supports(primary: primary, secondary: secondary) }

    /// Returns a copy that satisfies `ComponentVisual.supports`, dropping line 2 or falling back to text.
    func normalized() -> MenuBarComponent {
        var c = self
        if c.secondary == c.primary { c.secondary = nil }
        if c.tertiary == c.primary || c.tertiary == c.secondary || !c.visual.allowsThirdLine { c.tertiary = nil }
        if c.secondary == nil, let t = c.tertiary { c.secondary = t; c.tertiary = nil }
        if !c.visual.supports(primary: c.primary, secondary: c.secondary) {
            if c.visual.supports(primary: c.primary, secondary: nil) {
                c.secondary = nil
                c.tertiary = nil
            } else {
                c.visual = c.primary == .connection ? .dot : (c.secondary == nil ? .text : .stacked2)
                if !c.visual.supports(primary: c.primary, secondary: c.secondary) { c.secondary = nil }
            }
        }
        return c
    }

    var fields: [DataField] { [primary] + [secondary, tertiary].compactMap(\.self) }

    /// Cihaz pili bileşeni (örn. "📱 79").
    static func device(_ id: String, name: String? = nil) -> MenuBarComponent {
        var c = MenuBarComponent(.batteryLevel, visual: .batteryCapsule)
        c.deviceID = id
        c.deviceName = name
        return c
    }

    var title: String {
        if deviceID != nil { return (deviceName ?? "Cihaz") + " pili" }
        return fields.map(\.displayName).joined(separator: " + ")
    }

    var shortTitle: String {
        if let deviceName { return deviceName }
        return fields.map(\.label).joined(separator: " / ")
    }

    func isEquivalent(to other: MenuBarComponent) -> Bool {
        var a = self
        a.id = other.id
        a.panelKind = other.panelKind // tıklama paneli görünüm eşleştirmesini (preset) etkilemez
        return a == other
    }

    /// A fresh copy with a new identity, used when adding from the library or a preset.
    func duplicated() -> MenuBarComponent {
        var c = self
        c.id = UUID()
        return c
    }
}
